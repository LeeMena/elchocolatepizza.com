const dictionaries: Record<Lang, Dict> = { en, es }

// Translator bound to the active language. Falls back to English, then the key.
export function getT(lang: Lang) {
  return (key: string): string => dictionaries[lang][key] ?? dictionaries.en[key] ?? key
}

// Pick the right side of a bilingual field.
export const pick = <T extends { en: string; es: string }>(b: T | undefined, lang: Lang) => (b ? b[lang] || b.en : '')

// Dev-time guard: every Spanish key must exist in English (and vice versa).
export const missingKeys = () => ({
  missingInEs: Object.keys(en).filter((k) => !(k in es)),
  missingInEn: Object.keys(es).filter((k) => !(k in en)),
})
