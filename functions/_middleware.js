// Cloudflare Pages middleware: SPA fallback + edge <head> rewriting.
//
// Link-preview scrapers and non-JS crawlers never run React, so without this
// they'd see the homepage <head> on every URL. For each known route we rewrite
// <title>, description, canonical and og:/twitter: tags, and put the page's
// real content (menu, hours…) into #root. React replaces it on mount.
//
// Also handled here (guaranteed to run regardless of _redirects precedence):
//   - www -> apex canonical host (single-hop 301)
//   - legacy URLs from the previous static site (301)
//   - trailing-slash canonicalization (301)
//   - real HTTP 404 + noindex for unknown routes
//
// route-meta.json is generated by scripts/generate-route-meta.mjs (npm prebuild).
// Do not edit it by hand.

import routeMeta from './route-meta.json'

const BASE_URL = 'https://elchocolatepizza.com'

const ASSET_RE = /\.(js|css|map|png|jpg|jpeg|gif|webp|avif|svg|ico|woff2?|ttf|otf|json|xml|txt|pdf|webmanifest|html|mp4|webm)$/
const NON_HTML_FILE_RE = /\.(js|css|map|png|jpg|jpeg|gif|webp|avif|svg|ico|woff2?|ttf|otf|json|xml|txt|pdf|webmanifest|mp4|webm)$/

const LEGACY_REDIRECTS = {
  '/index.html': '/',
  '/menu.html': '/menu',
  '/menu/': '/menu',
  '/our-story': '/our-pizza',
  '/about': '/our-pizza',
  '/contact': '/visit',
  '/location': '/visit',
  '/locations': '/visit',
  '/hours': '/visit',
  '/order-online': '/order',
}

const setContent = (text) => ({ element: (el) => el.setInnerContent(text) })
const setAttr = (name, value) => ({ element: (el) => el.setAttribute(name, value) })
const appendHtml = (html) => ({ element: (el) => el.append(html, { html: true }) })
const setHtml = (html) => ({ element: (el) => el.setInnerContent(html, { html: true }) })

const escapeHtml = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))

const SITE_NAV =
  '<nav><ul>' +
  [['/', 'Home'], ['/menu', 'Menu'], ['/our-pizza', 'Our Pizza'], ['/order', 'Order'], ['/visit', 'Visit']]
    .map(([href, label]) => `<li><a href="${href}">${label}</a></li>`).join('') +
  '</ul></nav>'

function fallbackBody(meta) {
  const h1 = meta.h1 || meta.title.split(' | ')[0]
  return `<main style="max-width:60ch;margin:4rem auto;padding:0 1rem;font-family:system-ui;color:#fff4e2">` +
    `<h1>${escapeHtml(h1)}</h1><p>${escapeHtml(meta.description)}</p>${meta.body || ''}` +
    `<footer><p>Pizzeria El Chocolate · 899 Pondella Rd, North Fort Myers, FL 33903 · ` +
    `<a href="tel:+12399469006">(239) 946-9006</a></p>${SITE_NAV}</footer></main>`
}

function rewriteHead(shell, path, meta, status) {
  const url = `${BASE_URL}${path}`
  const rw = new HTMLRewriter()
    .on('title', setContent(meta.title))
    .on('meta[name="description"]', setAttr('content', meta.description))
    .on('link[rel="canonical"]', setAttr('href', url))
    .on('meta[property="og:title"]', setAttr('content', meta.title))
    .on('meta[property="og:description"]', setAttr('content', meta.description))
    .on('meta[property="og:url"]', setAttr('content', url))
    .on('meta[name="twitter:title"]', setAttr('content', meta.title))
    .on('meta[name="twitter:description"]', setAttr('content', meta.description))
    .on('div#root', setHtml(fallbackBody(meta)))
  if (meta.noindex) rw.on('head', appendHtml('<meta name="robots" content="noindex, follow">'))

  const out = rw.transform(shell)
  if (status === 200) return out
  return new Response(out.body, { status, headers: out.headers })
}

export async function onRequest(context) {
  const { request, next } = context
  const url = new URL(request.url)
  const path = url.pathname

  // Canonical host: www -> apex
  if (url.hostname.startsWith('www.')) {
    return Response.redirect(`https://${url.hostname.slice(4)}${path}${url.search}`, 301)
  }

  const legacy = LEGACY_REDIRECTS[path]
  if (legacy) return Response.redirect(`${url.origin}${legacy}${url.search}`, 301)

  // Static assets: serve directly; a missing file must 404, not return the SPA shell
  if (path.startsWith('/assets/') || path.startsWith('/images/') || ASSET_RE.test(path)) {
    const asset = await next()
    if (NON_HTML_FILE_RE.test(path) && (asset.headers.get('content-type') || '').startsWith('text/html')) {
      return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain; charset=utf-8' } })
    }
    return asset
  }

  if (path.length > 1 && path.endsWith('/')) {
    return Response.redirect(`${url.origin}${path.replace(/\/+$/, '') || '/'}${url.search}`, 301)
  }

  const shell = await next('/index.html')
  const meta = routeMeta[path]
  if (!meta) return rewriteHead(shell, path, { ...routeMeta['__404__'], noindex: true }, 404)
  return rewriteHead(shell, path, meta, 200)
}
